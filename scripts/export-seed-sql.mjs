// Writes supabase/seed.sql from web/js/seedData.js, so the Supabase library matches the app's bundled content.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const ctx = {};
vm.createContext(ctx);
vm.runInContext(`${readFileSync("web/js/seedData.js", "utf8")}\n;this.R = SEED_RESOURCES; this.P = SEED_BIBLE_PLANS;`, ctx);

const q = (v) => (v === undefined || v === null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const tags = (t) => (t && t.length ? `array[${t.map(q).join(", ")}]` : "'{}'");
const isSample = (r) => (r.is_sample === 0 ? "false" : "true");
const row = (r) =>
  `(${[q(r.type), q(r.title), q(r.subtitle), q(r.body), q(r.url), q(r.contact), q(r.area), q(r.duration_min), tags(r.tags), isSample(r)].join(", ")})`;
const cols = "(type, title, subtitle, body, url, contact, area, duration_min, tags, is_sample)";

const out = [
  "-- Generated by scripts/export-seed-sql.mjs from web/js/seedData.js. Do not edit by hand.",
  "-- Safe to re-run: it replaces sample rows (and their plan days) and never touches real (is_sample = false) rows or check-ins.",
  "begin;",
  "delete from public.resources where is_sample;",
  "",
  `insert into public.resources ${cols} values`,
  ctx.R.map(row).join(",\n") + ";",
];

for (const plan of ctx.P) {
  const days = plan.days.map((d) => `(${d.day_number}, ${q(d.reference)}, ${q(d.reflection)})`).join(",\n    ");
  out.push(
    "",
    `with plan as (insert into public.resources ${cols} values ${row(plan.resource)} returning id)`,
    "insert into public.bible_plan_days (plan_id, day_number, reference, reflection)",
    `select plan.id, d.day_number, d.reference, d.reflection from plan, (values\n    ${days}\n) as d(day_number, reference, reflection);`
  );
}
out.push("", "commit;", "");

writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`supabase/seed.sql: ${ctx.R.length} resources + ${ctx.P.length} bible plans (${ctx.P.reduce((n, p) => n + p.days.length, 0)} days)`);
