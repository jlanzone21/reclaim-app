// One-off importer: reads a recovery-groups CSV and writes a SQL migration that inserts them as
// real (is_sample = false) small_group resources. Safe to re-run: it only ever inserts rows whose
// source_url isn't already present, so running it again with the same CSV is a no-op.
//
// Usage: node scripts/import-small-groups.mjs <path-to-csv> [output.sql]
import { readFileSync, writeFileSync } from "node:fs";

const [, , csvPath, outPath = "supabase/migrations/" + stamp() + "_import_small_groups.sql"] = process.argv;
if (!csvPath) {
  console.error("Usage: node scripts/import-small-groups.mjs <path-to-csv> [output.sql]");
  process.exit(1);
}

function stamp() {
  return new Date().toISOString().replace(/[-:]/g, "").replace(/\..+/, "").replace("T", "");
}

// Minimal RFC4180 parser: handles quoted fields, embedded commas, and "" as an escaped quote.
function parseCsv(text) {
  const rows = [];
  let row = [],
    field = "",
    inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        inQuotes = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f.trim() !== ""));
}

const text = readFileSync(csvPath, "utf8");
const [header, ...rows] = parseCsv(text);
const records = rows.map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));

const q = (v) => (v === undefined || v === null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === undefined || v === null || v === "" ? "null" : Number(v));
const jsonb = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;

function composeContact(r) {
  return [r.contact_name, r.contact_phone, r.contact_email].filter(Boolean).join(" · ") || null;
}
function composeBody(r) {
  return [r.curriculum, r.meeting_format, r.meeting_schedule, r.eligibility].filter(Boolean).join(" · ") || null;
}
function composeArea(r) {
  return [r.city, r.state].filter(Boolean).join(", ") || r.city || r.state || null;
}

const detailKeys = [
  "legacy_id", "listing_type", "verification_status", "accepting_new_members",
  "source_url", "availability_note", "postal_code", "street_address",
  "research_compiled_on", "notes",
];

const rowsSql = records.map((r) => {
  const details = Object.fromEntries(detailKeys.map((k) => [k, r[k] || null]).filter(([, v]) => v !== null));
  return `(${[
    q("small_group"),
    q(r.group_name),
    q(r.organization_name),
    q(composeBody(r)),
    q(r.website_url || r.source_url),
    q(composeContact(r)),
    q(composeArea(r)),
    "null", // duration_min: not applicable to small groups
    "'{}'", // tags: not used for filtering small_group_finder today
    "false", // is_sample: this is real, rights-cleared directory data
    q(r.city),
    q(r.state),
    num(r.latitude),
    num(r.longitude),
    jsonb(details),
  ].join(", ")})`;
});

const cols = "(type, title, subtitle, body, url, contact, area, duration_min, tags, is_sample, city, state, latitude, longitude, details)";
// A VALUES list with an all-null column (duration_min, latitude, longitude here) can't infer that
// column's type on its own, so every column is cast explicitly in the outer select instead of
// relying on `v.*` to match the target table's types.
const selectCols = [
  "v.type::text", "v.title::text", "v.subtitle::text", "v.body::text", "v.url::text", "v.contact::text",
  "v.area::text", "v.duration_min::integer", "v.tags::text[]", "v.is_sample::boolean", "v.city::text",
  "v.state::text", "v.latitude::numeric", "v.longitude::numeric", "v.details::jsonb",
].join(", ");

const out = [
  `-- Generated by scripts/import-small-groups.mjs from ${csvPath}. Do not edit by hand; re-run the script instead.`,
  "-- Safe to re-run: only inserts rows whose url isn't already present, so a repeat run is a no-op.",
  "begin;",
  "",
  `insert into public.resources ${cols}`,
  `select ${selectCols} from (values`,
  rowsSql.join(",\n"),
  `) as v${cols}`,
  "where not exists (",
  "  select 1 from public.resources r",
  "  where r.type = 'small_group' and r.url is not distinct from v.url and r.title = v.title",
  ");",
  "",
  "commit;",
  "",
].join("\n");

writeFileSync(outPath, out);
console.log(`${outPath}: ${records.length} small groups from ${csvPath}`);
